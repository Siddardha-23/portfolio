# CLDR recognises some two-letter codes that are not ISO 3166-1 countries.
# "UK" is the dangerous one: left alone it becomes a second bucket beside "GB"
# and splits British visitors across two rows.
_CODE_ALIASES: Dict[str, str] = {
    "UK": "GB",
}

# Groupings and placeholders that are not places anyone visits from.
_NON_COUNTRY_CODES = frozenset({
    "EU", "EZ", "UN", "QO", "XA", "XB", "ZZ", "XX",
})

# Values that mean "not geolocated" and must never be plotted.
JUNK_LOCATIONS = frozenset({
    "", "-", "n/a", "na", "null", "none", "undefined",
    "unknown", "local", "localhost", "local development", "development",
    "xx", "zz", "private", "reserved",
})

_NAME_TO_CODE: Dict[str, str] = {
    name.lower(): code for code, name in COUNTRY_CODE_TO_NAME.items()
}
# Aliases last, so they win over any CLDR name they collide with.
_NAME_TO_CODE.update(_ALIASES)


def resolve_country_code(raw: Optional[str]) -> Optional[str]:
    """
    Turn a code, a display name or a legacy alias into one canonical alpha-2 code.

    Returns None for junk and for anything unrecognisable, so callers drop the row
    rather than group unrelated traffic under a value nobody can read.
    """
    if not raw:
        return None
    value = str(raw).strip()
    if not value or value.lower() in JUNK_LOCATIONS:
        return None

    # Aliases are checked first so "UK" resolves to GB rather than being taken
    # at face value as its own code.
    code = _NAME_TO_CODE.get(value.lower())

    if code is None and len(value) == 2 and value.isalpha():
        code = value.upper()

    if code is None:
        return None

    code = _CODE_ALIASES.get(code, code)
    if code in _NON_COUNTRY_CODES or code not in COUNTRY_CODE_TO_NAME:
        return None
    return code


def country_name(code: Optional[str]) -> Optional[str]:
    """Display name for an alpha-2 code, or None when the code is unknown."""
    if not code:
        return None
    return COUNTRY_CODE_TO_NAME.get(str(code).strip().upper())
