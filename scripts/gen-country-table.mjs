/**
 * Generates portfolio-backend/shared/python/utils/countries.py.
 *
 * The frontend names countries with Intl.DisplayNames. The backend needs the same
 * names for stored records, admin views and emails, so this emits a Python table
 * from that identical CLDR data rather than a second hand-maintained dictionary
 * that can drift out of agreement with the UI.
 *
 * Run from portfolio-frontend:  node ../scripts/gen-country-table.mjs
 */
import { writeFileSync } from 'node:fs';

const OUT = '../portfolio-backend/shared/python/utils/countries.py';

const dn = new Intl.DisplayNames(['en'], { type: 'region' });

const rows = [];
for (let a = 65; a <= 90; a++) {
    for (let b = 65; b <= 90; b++) {
        const code = String.fromCharCode(a, b);
        let name;
        try {
            name = dn.of(code);
        } catch {
            continue;
        }
        // Intl echoes the input back for unassigned codes.
        if (!name || name === code) continue;
        rows.push([code, name]);
    }
}

const table = rows
    .map(([code, name]) => `    ${JSON.stringify(code)}: ${JSON.stringify(name)},`)
    .join('\n');

const py = `"""
ISO 3166-1 alpha-2 country codes and their display names.

GENERATED by scripts/gen-country-table.mjs from CLDR via Intl.DisplayNames.
Do not edit by hand; re-run the generator instead.

This exists because the visitor pipeline previously carried a 44-entry dictionary,
so every country outside it reached the UI as a bare two-letter code -- the map
rendered "NP" and "LK" as though those were country names. It also let one country
occupy two buckets, its visitors split between the code and the spelled-out name.
"""
from typing import Dict, Optional

COUNTRY_CODE_TO_NAME: Dict[str, str] = {
${table}
}

# Spellings that have been written into the database over time, or that people
# reasonably type. Keys are lowercased.
_ALIASES: Dict[str, str] = {
    "usa": "US",
    "united states of america": "US",
    "america": "US",
    "uk": "GB",
    "great britain": "GB",
    "britain": "GB",
    "england": "GB",
    "scotland": "GB",
    "wales": "GB",
    "uae": "AE",
    "korea": "KR",
    "south korea": "KR",
    "republic of korea": "KR",
    "russia": "RU",
    "russian federation": "RU",
    "vietnam": "VN",
    "viet nam": "VN",
    "czech republic": "CZ",
    "czechia": "CZ",
    "turkey": "TR",
    "turkiye": "TR",
    "ivory coast": "CI",
    "cape verde": "CV",
    "swaziland": "SZ",
    "burma": "MM",
    "hong kong": "HK",
    "macau": "MO",
    "holland": "NL",
    "the netherlands": "NL",
    "dr congo": "CD",
    "democratic republic of the congo": "CD",
    "vatican": "VA",
    "holy see": "VA",
}

# CLDR recognises some two-letter codes that are not ISO 3166-1 countries.
# "UK" is the dangerous one: left alone it becomes a second bucket beside "GB"
# and splits British visitors across two rows.
_CODE_ALIASES: Dict[str, str] = {
    "UK": "GB",
}

# Groupings and placeholders that are not places anyone visits from.
_NON_COUNTRY_CODES = frozenset({
    "EU", "EZ", "UN", "QO", "XA", "XB", "ZZ", "XX",
})

# Values that mean "not geolocated" and must never be plotted.
JUNK_LOCATIONS = frozenset({
    "", "-", "n/a", "na", "null", "none", "undefined",
    "unknown", "local", "localhost", "local development", "development",
    "xx", "zz", "private", "reserved",
})

_NAME_TO_CODE: Dict[str, str] = {
    name.lower(): code for code, name in COUNTRY_CODE_TO_NAME.items()
}
# Aliases last, so they win over any CLDR name they collide with.
_NAME_TO_CODE.update(_ALIASES)


def resolve_country_code(raw: Optional[str]) -> Optional[str]:
    """
    Turn a code, a display name or a legacy alias into one canonical alpha-2 code.

    Returns None for junk and for anything unrecognisable, so callers drop the row
    rather than group unrelated traffic under a value nobody can read.
    """
    if not raw:
        return None
    value = str(raw).strip()
    if not value or value.lower() in JUNK_LOCATIONS:
        return None

    # Aliases are checked first so "UK" resolves to GB rather than being taken
    # at face value as its own code.
    code = _NAME_TO_CODE.get(value.lower())

    if code is None and len(value) == 2 and value.isalpha():
        code = value.upper()

    if code is None:
        return None

    code = _CODE_ALIASES.get(code, code)
    if code in _NON_COUNTRY_CODES or code not in COUNTRY_CODE_TO_NAME:
        return None
    return code


def country_name(code: Optional[str]) -> Optional[str]:
    """Display name for an alpha-2 code, or None when the code is unknown."""
    if not code:
        return None
    return COUNTRY_CODE_TO_NAME.get(str(code).strip().upper())
`;

writeFileSync(OUT, py);
console.log(`regions: ${rows.length} -> ${OUT}`);
